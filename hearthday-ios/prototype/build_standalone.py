#!/usr/bin/env python3
"""Inline app.css, core.js and app.js into hearthday-prototype.html.

The result is one self-contained file that opens by double-clicking on Windows, macOS or Linux, with no server
or network access. CI rebuilds it and fails if the committed copy is out of date.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "hearthday-prototype.html"


def read(name: str) -> str:
    text = (HERE / name).read_text(encoding="utf-8")
    if "</script" in text.lower() or "</style" in text.lower():
        raise SystemExit(f"{name} contains a closing tag that would break inlining")
    return text


def main() -> None:
    html = (HERE / "index.html").read_text(encoding="utf-8")
    replacements = {
        '<link rel="stylesheet" href="app.css" />': f"<style>\n{read('app.css')}</style>",
        '<script src="core.js"></script>': f"<script>\n{read('core.js')}</script>",
        '<script src="app.js"></script>': f"<script>\n{read('app.js')}</script>",
    }
    for tag, inline in replacements.items():
        if tag not in html:
            raise SystemExit(f"index.html no longer contains {tag!r}")
        html = html.replace(tag, inline)
    header = "<!-- Generated by prototype/build_standalone.py from index.html, app.css, core.js and app.js. Do not edit. -->\n"
    OUT.write_text(header + html, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(HERE.parent)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
